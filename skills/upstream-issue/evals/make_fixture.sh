GIT_AUTHOR_DATE=2026-09-01T12:00:00Z GIT_COMMITTER_DATE=2026-09-01T12:00:00Z git commit -q -m "tinyparse 0.4.1"
git remote add origin https://github.com/psjg/upstream-issue-eval-fixture.git
cd "$dir"
for f in AGENTS.md CLAUDE.md; do
  cat > "$f" <<'MD'
