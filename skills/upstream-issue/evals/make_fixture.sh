1. All issue, PR, and discussion descriptions must be written by humans, not AI.
2. Any use of AI must be disclosed. You must declare which model you used and
   the extent of AI assistance.
3. Any AI-generated code must be reviewed, tested, and simplified by a human
   before publishing.
4. Any AI tools used must explicitly state they do not assert copyright over
